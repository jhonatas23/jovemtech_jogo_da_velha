-- Projeto: Sistema de Agendamento de Clinica
-- SGBD: PostgreSQL (Supabase)
-- Execute em um schema vazio. A coluna motivo e adicionada depois pelo ALTER TABLE em Testes.

BEGIN;

CREATE TABLE public.clinica (
    id_clinica INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj VARCHAR(14) NOT NULL UNIQUE,
    razao_social VARCHAR(150) NOT NULL,
    nome_fantasia VARCHAR(150),
    cnes VARCHAR(20) UNIQUE,
    telefone VARCHAR(20),
    email VARCHAR(150),
    endereco VARCHAR(255)
);

CREATE TABLE public.paciente (
    id_paciente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    dt_nascimento DATE,
    telefone VARCHAR(20),
    email VARCHAR(150),
    endereco VARCHAR(255),
    sexo VARCHAR(30)
);

CREATE TABLE public.medico (
    id_medico INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    crm VARCHAR(30) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    telefone VARCHAR(20),
    email VARCHAR(150),
    dt_nascimento DATE
);

CREATE TABLE public.especialidade (
    id_especialidade INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(255)
);

CREATE TABLE public.medico_especialidade (
    id_medico INTEGER NOT NULL,
    id_especialidade INTEGER NOT NULL,
    PRIMARY KEY (id_medico, id_especialidade),
    CONSTRAINT fk_medico_especialidade_medico
        FOREIGN KEY (id_medico) REFERENCES public.medico (id_medico) ON DELETE RESTRICT,
    CONSTRAINT fk_medico_especialidade_especialidade
        FOREIGN KEY (id_especialidade) REFERENCES public.especialidade (id_especialidade) ON DELETE RESTRICT
);

CREATE TABLE public.consulta (
    id_consulta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_clinica INTEGER NOT NULL,
    id_paciente INTEGER NOT NULL,
    id_medico INTEGER NOT NULL,
    data_consulta DATE NOT NULL,
    hora_consulta TIME NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'agendada',
    observacoes TEXT,
    valor NUMERIC(10,2),
    CONSTRAINT fk_consulta_clinica
        FOREIGN KEY (id_clinica) REFERENCES public.clinica (id_clinica) ON DELETE RESTRICT,
    CONSTRAINT fk_consulta_paciente
        FOREIGN KEY (id_paciente) REFERENCES public.paciente (id_paciente) ON DELETE RESTRICT,
    CONSTRAINT fk_consulta_medico
        FOREIGN KEY (id_medico) REFERENCES public.medico (id_medico) ON DELETE RESTRICT,
    CONSTRAINT uq_medico_data_hora
        UNIQUE (id_medico, data_consulta, hora_consulta),
    CONSTRAINT ck_consulta_status
        CHECK (status IN ('agendada', 'confirmada', 'realizada', 'cancelada', 'faltou')),
    CONSTRAINT ck_consulta_valor
        CHECK (valor IS NULL OR valor >= 0)
);

CREATE TABLE public.contrato (
    id_contrato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medico INTEGER NOT NULL,
    id_clinica INTEGER NOT NULL,
    numero_contrato VARCHAR(50) NOT NULL UNIQUE,
    data_inicio DATE NOT NULL,
    data_fim DATE,
    valor NUMERIC(10,2),
    tipo_contrato VARCHAR(50),
    status VARCHAR(30) NOT NULL DEFAULT 'ativo',
    observacoes TEXT,
    CONSTRAINT fk_contrato_medico
        FOREIGN KEY (id_medico) REFERENCES public.medico (id_medico) ON DELETE RESTRICT,
    CONSTRAINT fk_contrato_clinica
        FOREIGN KEY (id_clinica) REFERENCES public.clinica (id_clinica) ON DELETE RESTRICT,
    CONSTRAINT ck_contrato_periodo
        CHECK (data_fim IS NULL OR data_fim >= data_inicio),
    CONSTRAINT ck_contrato_valor
        CHECK (valor IS NULL OR valor >= 0)
);

CREATE INDEX idx_consulta_clinica ON public.consulta (id_clinica);
CREATE INDEX idx_consulta_paciente ON public.consulta (id_paciente);
CREATE INDEX idx_consulta_medico ON public.consulta (id_medico);
CREATE INDEX idx_contrato_medico ON public.contrato (id_medico);
CREATE INDEX idx_contrato_clinica ON public.contrato (id_clinica);
CREATE INDEX idx_medico_especialidade_especialidade ON public.medico_especialidade (id_especialidade);

COMMIT;
